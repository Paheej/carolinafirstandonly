/**
 * Builds packages/database/supabase/migrations/0019_season_3_reference.sql from
 * out/season-3.json (takeout.ts run on season-3-manifest.json): the 40K Season III
 * rules pages the first import missed, as reference pages on season-3.
 *
 *   node src/build-season-3.mjs
 */
import { readFile, writeFile } from 'node:fs/promises';

const here = new URL('..', import.meta.url).pathname;
const manifest = JSON.parse(await readFile(`${here}season-3-manifest.json`, 'utf8'));
const data = JSON.parse(await readFile(`${here}out/season-3.json`, 'utf8'));

const links = new Map();
for (const it of manifest.items) {
    links.set(`${it.page.replace(/ /g, '%20')}.html`, `/archive/pages/${it.slug}`);
    links.set(`${encodeURIComponent(it.page)}.html`, `/archive/pages/${it.slug}`);
}

function clean(md) {
    // Image-links split over blank lines: "[\n\n![](x)\n\n](y)" -> "[![](x)](y)"
    md = md.replace(/\[\s+(!\[[^\]]*\]\([^)]*\))\s+\]\(/g, '[$1](');
    md = md.replace(/\]\(([^)\s]+\.html)\)/g, (full, href) => {
        const to = links.get(href);
        if (!to) throw new Error(`unmapped link ${href}`);
        return `](${to})`;
    });
    md = md.replace(/^(\s*#\s[^\n]*\n)+/, '').trimStart();
    md = md.replace(/\n+Link for developer use:[^\n]*/g, '');
    md = md.replace(/\n+\s*20\d\d\.\s*$/, '').trimEnd();
    return md;
}
const dq = (s) => {
    for (const tag of ['md', 'md1', 'md2', 'mdx']) if (!s.includes(`$${tag}$`)) return `$${tag}$${s}$${tag}$`;
    throw new Error('no dollar tag');
};
const str = (s) => `'${s.replace(/'/g, "''")}'`;

const out = [
    '-- ============================================================================',
    '-- 0019_season_3_reference.sql — 40K Season III rules pages from the old',
    '-- Google Site (house rules, campaign turns, victory conditions, map, move',
    '-- examples, FAQ, three Crusade scenarios), as reference pages on season-3.',
    '-- Generated by tools/migrate-google-site/src/build-season-3.mjs.',
    '-- ============================================================================',
    '',
];
manifest.items.forEach((it, i) => {
    const r = data.results[it.slug];
    if (!r) throw new Error(`missing ${it.slug}`);
    out.push(
        'insert into public.archive_pages (slug, title, body_md, category, display_order, season_id)',
        `select ${str(it.slug)}, ${str(it.title)}, ${dq(clean(r.bodyMd))}, 's3-reference', ${i + 1}, s.id from public.seasons s where s.slug = 'season-3'`,
        'on conflict (slug) do nothing;',
        '',
    );
});
const target = `${here}../../packages/database/supabase/migrations/0019_season_3_reference.sql`;
await writeFile(target, out.join('\n'), 'utf8');
console.log(`wrote ${target}`);
