/**
 * Builds packages/database/supabase/migrations/0018_old_world_campaign.sql
 * from out/old-world.json (takeout.ts run on old-world-manifest.json).
 *
 *   node src/build-old-world.mjs
 *
 * - Old World Campaign season (Oct 2024 - Jul 2025), from "Multiplayer Campaign"
 * - its rules pages as archive_pages on that season
 * - PJ's nine 2024 Empire games as recaps on that season, dated by game month
 * Internal "Page Name.html" links are rewritten to archive routes, including
 * links wrapped around images, and duplicate leading H1s are dropped.
 */
import { readFile, writeFile } from 'node:fs/promises';

const here = new URL('..', import.meta.url).pathname;
const manifest = JSON.parse(await readFile(`${here}old-world-manifest.json`, 'utf8'));
const data = JSON.parse(await readFile(`${here}out/old-world.json`, 'utf8'));

const ROUTES = { season: '/archive/seasons', event: '/archive/events', recap: '/archive/recaps', page: '/archive/pages' };
const links = new Map();
for (const it of manifest.items) {
    const to = `${ROUTES[it.kind]}/${it.slug}`;
    links.set(`${it.page.replace(/ /g, '%20')}.html`, to);
    links.set(`${encodeURIComponent(it.page)}.html`, to);
}

function clean(md) {
    // Image-links split over blank lines: "[\n\n![](x)\n\n](y)" -> "[![](x)](y)"
    md = md.replace(/\[\s+(!\[[^\]]*\]\([^)]*\))\s+\]\(/g, '[$1](');
    md = md.replace(/\]\(([^)\s]+\.html)\)/g, (full, href) => {
        const to = links.get(href);
        if (!to) throw new Error(`unmapped link ${href}`);
        return `](${to})`;
    });
    // Drop the leading run of "# Heading" lines; the page head shows the title.
    md = md.replace(/^(\s*#\s[^\n]*\n)+/, '').trimStart();
    // Footer leftovers ("2024." on its own line at the end).
    md = md.replace(/\n+\s*20\d\d\.\s*$/, '').trimEnd();
    return md;
}

const dq = (s) => {
    for (const tag of ['md', 'md1', 'md2', 'mdx']) if (!s.includes(`$${tag}$`)) return `$${tag}$${s}$${tag}$`;
    throw new Error('no dollar tag');
};
const str = (s) => `'${s.replace(/'/g, "''")}'`;

const r = (slug) => {
    const x = data.results[slug];
    if (!x) throw new Error(`missing ${slug}`);
    return x;
};

const season = r('old-world-campaign');
const PAGES = [
    ['ow-territory-chart', 1],
    ['ow-fighting-battles', 2],
    ['ow-scenarios', 3],
    ['ow-current-status', 4],
    ['ow-custom-cards', 5],
    ['ow-2024-battle-reports', 6],
];
// Game month from each report's "Month and Year" line; day keeps them in played order.
const RECAP_DATES = {
    'ow-emp-vs-bret-feb24': '2024-02-10',
    'ow-emp-vs-he-feb24': '2024-02-24',
    'ow-emp-vs-gob-mar24': '2024-03-09',
    'ow-emp-vs-gob-mar24-2': '2024-03-23',
    'ow-emp-vs-daemon-apr24': '2024-04-06',
    'ow-emp-vs-daemon-apr24-2': '2024-04-13',
    'ow-emp-vs-bret-apr24': '2024-04-20',
    'ow-emp-vs-ogre-apr24': '2024-04-24',
    'ow-emp-vs-wood-apr24': '2024-04-27',
};

const currentStatus =
    'The campaign map and territory standings were kept in a Google Slides deck, updated weekly as battles were reported.\n\n' +
    '[Open the Old World campaign map](https://docs.google.com/presentation/d/14NdWlOF6kT1VOn_5_VLyt6HYscCaryX0XALb0_YrXm4/present)';

const out = [
    '-- ============================================================================',
    '-- 0018_old_world_campaign.sql — the Warhammer Fantasy (Old World) campaign',
    '-- from the old Google Site, which the first import missed.',
    '-- Generated by tools/migrate-google-site/src/build-old-world.mjs; images are',
    '-- on ImageKit under /seasons/old-world-campaign, /pages/ow-*, /recaps/ow-*.',
    '-- ============================================================================',
    '',
    'insert into public.seasons (slug, name, year, starts_on, ends_on, status, game_system, game_edition, display_order, hero_image_url, description_md)',
    `values ('old-world-campaign', 'Old World Campaign', 2024, '2024-10-01', '2025-07-26', 'completed', 'Warhammer Fantasy', 'Old World', 6, ${
        season.heroImageUrl ? str(season.heroImageUrl) : 'null'
    },`,
    `    ${dq(clean(season.bodyMd))})`,
    'on conflict (slug) do nothing;',
    '',
];

for (const [slug, order] of PAGES) {
    const p = r(slug);
    const body = slug === 'ow-current-status' ? currentStatus : clean(p.bodyMd);
    out.push(
        'insert into public.archive_pages (slug, title, body_md, category, display_order, season_id)',
        `select ${str(slug)}, ${str(p.title)}, ${dq(body)}, 'old-world-reference', ${order}, s.id from public.seasons s where s.slug = 'old-world-campaign'`,
        'on conflict (slug) do nothing;',
        '',
    );
}

for (const [slug, date] of Object.entries(RECAP_DATES)) {
    const x = r(slug);
    out.push(
        'insert into public.recaps (slug, season_id, title, body_md, published_at)',
        `select ${str(slug)}, s.id, ${str(x.title)}, ${dq(clean(x.bodyMd))}, '${date} 12:00:00-05' from public.seasons s where s.slug = 'old-world-campaign'`,
        'on conflict (slug) do nothing;',
        '',
    );
}

const target = `${here}../../packages/database/supabase/migrations/0018_old_world_campaign.sql`;
await writeFile(target, out.join('\n'), 'utf8');
console.log(`wrote ${target} (${out.length} lines)`);
